#!/usr/bin/env bash
###############################################################################
# update-cato-pop-cidrs.sh – refresh cato_pop_cidrs in terraform.tfvars
#
# Downloads the Cato POP geo-IP feed, keeps the IPv4 prefixes, consolidates
# them (adjacent/overlapping CIDRs are merged) and rewrites the block between
# the "BEGIN/END cato_pop_cidrs" markers in terraform.tfvars (appended if the
# markers do not exist yet).
#
# USAGE
#   ./update-cato-pop-cidrs.sh [tfvars-file]
#
# ENV
#   CATO_FEED_URL  – override the feed URL
###############################################################################
set -euo pipefail

die() { printf '❌  %s\n' "$*" >&2; exit 1; }

BASE_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
TFVARS="${1:-${BASE_DIR}/terraform.tfvars}"
FEED_URL="${CATO_FEED_URL:-https://geoipfeed.catonetworks.com/cato_ip2geo_feed.csv}"

command -v curl >/dev/null    || die "curl is required"
command -v python3 >/dev/null || die "python3 is required"
[ -f "${TFVARS}" ] || die "tfvars file not found: ${TFVARS}"

feed=$(mktemp); trap 'rm -f "${feed}"' EXIT
echo "⬇️   Downloading ${FEED_URL}"
curl --fail --silent --show-error --location --proto '=https' --max-time 60 \
  -o "${feed}" "${FEED_URL}" || die "Could not download the Cato POP feed"

python3 -I - "${feed}" "${TFVARS}" <<'PY'
import csv, ipaddress, os, shutil, sys, tempfile

feed, tfvars = sys.argv[1], sys.argv[2]
BEGIN, END = "# BEGIN cato_pop_cidrs", "# END cato_pop_cidrs"

nets, skipped = [], 0
with open(feed, newline="") as f:
    for row in csv.reader(f):
        if not row or row[0].lstrip().startswith("#"):
            continue
        try:
            n = ipaddress.ip_network(row[0].strip(), strict=False)
        except ValueError:
            skipped += 1
            continue
        if n.version == 4:          # the VPC is IPv4-only
            nets.append(n)

if not nets:
    sys.exit("❌  No IPv4 CIDRs found in the feed; leaving %s untouched" % tfvars)

merged = sorted(ipaddress.collapse_addresses(nets))
block = [BEGIN, "# Generated by update-cato-pop-cidrs.sh – do not edit by hand", "cato_pop_cidrs = ["]
block += ['  "%s",' % n for n in merged]
block += ["]", END]

text = open(tfvars).read()
if BEGIN in text and END in text:
    head, rest = text.split(BEGIN, 1)
    tail = rest.split(END, 1)[1]
    new = head + "\n".join(block) + tail
else:
    new = text.rstrip("\n") + "\n\n" + "\n".join(block) + "\n"

fd, tmp = tempfile.mkstemp(dir=os.path.dirname(os.path.abspath(tfvars)))
with os.fdopen(fd, "w") as f:
    f.write(new)
shutil.copymode(tfvars, tmp)
os.replace(tmp, tfvars)
print("✅  %d feed prefixes -> %d consolidated CIDRs written to %s (%d unparsable lines skipped)"
      % (len(nets), len(merged), tfvars, skipped))
PY
